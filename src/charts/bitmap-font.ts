const FALLBACK_GLYPH = '?';

/** Glyph rows as bit masks (bit 4 = leftmost column), one entry per row. */
const GLYPH_MASKS = new Map<string, readonly number[]>();
for (const [char, rows] of Object.entries(GLYPH_ROWS)) {
  if (rows.length !== GLYPH_HEIGHT || rows.some((row) => row.length !== GLYPH_WIDTH)) {
    throw new Error(`bitmap font glyph ${JSON.stringify(char)} is malformed`);
  }
  GLYPH_MASKS.set(
    char,
    rows.map((row) => [...row].reduce((mask, cell) => (mask << 1) | (cell === '#' ? 1 : 0), 0)),
  );
}

/** Return the row masks for a character, substituting `?` for anything unknown. */
export function glyphMasks(char: string): readonly number[] {
  return GLYPH_MASKS.get(char) ?? GLYPH_MASKS.get(FALLBACK_GLYPH)!;
}

/**
 * Reduce arbitrary text to the printable ASCII range the font covers.
 * Diacritics are folded to their base letter; anything else becomes `?`.
 */
export function fontText(value: string): string {
  return value
    .replace(/[\u2018\u2019\u201a\u2032]/g, "'")
    .replace(/[\u201c\u201d\u201e\u2033]/g, '"')
    .replace(/[\u2010-\u2015\u2212]/g, '-')
    .replace(/\u2026/g, '...')
    .replace(/\u00a0/g, ' ')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^\x20-\x7e]/g, FALLBACK_GLYPH);
}

/** Pixel width of `text` at `scale` (no trailing spacing column). */
export function textWidth(text: string, scale: number): number {
  if (text.length === 0) return 0;
  return (text.length * GLYPH_ADVANCE - 1) * scale;
}

export function textHeight(scale: number): number {
  return GLYPH_HEIGHT * scale;
}
