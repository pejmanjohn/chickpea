#!/usr/bin/env node
/**
 * The Durable Object RPC contract: every deployed object class's public
 * methods, with their resolved parameter and return types, recorded in
 * contracts/rpc-surface.json and judged against the commit the candidate
 * builds on. A held object serves its old build for minutes after a deploy,
 * so the two builds must be able to call each other.
 *
 *   npm run verify:rpc-contract                            # the working tree, against its base
 *   npm run verify:rpc-contract -- --update                # rewrite the snapshot, then judge
 *   npm run verify:rpc-contract -- --base REV              # judge against REV instead
 *   npm run verify:rpc-contract -- --base REV --head REV   # judge one commit against another
 *
 * The base defaults to where HEAD leaves origin/main. A revision without a
 * committed snapshot is read from its source. Exit 1 on a refused change or
 * a stale snapshot, 2 on a usage or structural error.
 * See docs/runbooks/releasing.md#rpc-contract.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readSurface, STATE_STORE_CLASS } from './lib/rpc-surface.mjs';
import { commitReasons, compareSurfaces, judge, subjectDigest, subjectValue } from './lib/rpc-contract.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SNAPSHOT = 'contracts/rpc-surface.json';
const SOURCE_PATHS = ['src', 'types', 'tsconfig.json', 'package.json', 'package-lock.json', 'wrangler.jsonc'];
const ABOUT = 'Generated by npm run verify:rpc-contract -- --update. Give a refused change its reason under "contract". See docs/runbooks/releasing.md#rpc-contract.';

class UsageError extends Error {}

export function parseArgs(argv) {
  const options = { update: false, base: undefined, head: undefined };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--update') { options.update = true; continue; }
    if (arg === '--base' || arg === '--head') {
      const value = argv[++index];
      if (!value || value.startsWith('-')) throw new UsageError(`${arg} requires a revision`);
      options[arg.slice(2)] = value;
      continue;
    }
    throw new UsageError(`Unknown argument: ${arg}`);
  }
  if (options.update && options.head) throw new UsageError('--update rewrites the working tree snapshot; it cannot combine with --head');
  return options;
}

function git(root, args, { input, allowFailure = false } = {}) {
  const result = spawnSync('git', ['-C', root, ...args], { input, maxBuffer: 512 * 1024 * 1024 });
  if (result.status !== 0) {
    if (allowFailure) return undefined;
    throw new UsageError(`git ${args.join(' ')} failed: ${result.stderr?.toString('utf8').trim()}`);
  }
  return result.stdout;
}

const shortRev = (root, rev) => git(root, ['rev-parse', '--short=10', `${rev}^{commit}`]).toString('utf8').trim();

function defaultBase(root) {
  const base = git(root, ['merge-base', 'HEAD', 'origin/main'], { allowFailure: true });
  if (!base) throw new UsageError('No merge base with origin/main. Fetch it, or name one with --base REV.');
  return base.toString('utf8').trim();
}

/** The snapshot as committed at `rev`, or undefined where it has none. */
function committedSnapshot(root, rev) {
  const text = git(root, ['show', `${rev}:${SNAPSHOT}`], { allowFailure: true });
  return text ? JSON.parse(text.toString('utf8')) : undefined;
}

/** The surface of a commit's source, read in a temporary copy that borrows this checkout's dependencies. */
function surfaceAtRevision(root, rev) {
  const directory = mkdtempSync(path.join(os.tmpdir(), 'rpc-contract-'));
  try {
    const paths = SOURCE_PATHS.filter((entry) => git(root, ['cat-file', '-e', `${rev}:${entry}`], { allowFailure: true }));
    const archive = git(root, ['archive', '--format=tar', rev, '--', ...paths]);
    const tar = spawnSync('tar', ['-x', '-C', directory], { input: archive, maxBuffer: 512 * 1024 * 1024 });
    if (tar.status !== 0) throw new Error(`tar failed: ${tar.stderr.toString('utf8').trim()}`);
    symlinkSync(path.join(root, 'node_modules'), path.join(directory, 'node_modules'), 'dir');
    return readSurface(directory);
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
}

const surfaceOf = ({ about: _about, contract: _contract, ...surface }) => surface;

function reasonsInRange(root, range) {
  const log = git(root, ['log', '--format=%B%x00', range]).toString('utf8');
  const shas = git(root, ['log', '--format=%H', range, '--', SNAPSHOT]).toString('utf8').split('\n').filter(Boolean);
  return {
    messages: log.split('\0'),
    sections: shas.map((sha) => committedSnapshot(root, sha)?.contract ?? {}),
  };
}

/** Snapshot reasons that still name their subject's current value; the rest no longer apply. */
export function keptReasons(contract, head) {
  return Object.fromEntries(Object.entries(contract ?? {})
    .filter(([subject, { to }]) => subjectDigest(subjectValue(head, subject)) === to)
    .sort(([a], [b]) => (a < b ? -1 : 1)));
}

export function snapshotText(head, contract) {
  return `${JSON.stringify({ about: ABOUT, schema: head.schema, contract, ...surfaceOf(head) }, null, 2)}\n`;
}

function describeAddition(change, head, read) {
  if (change.kind !== 'method-added') return change.says;
  const [className, method] = change.subject.split('.');
  const callers = read?.callersOf(method) ?? [];
  const where = callers.length ? ` Calls that may reach it in this build: ${callers.slice(0, 3).join(', ')}${callers.length > 3 ? ', ...' : ''}.` : '';
  if (className === STATE_STORE_CLASS && head.classes[className].methods[method].fallback) {
    return `${change.says}, behind withStoreFallback.${where}`;
  }
  const guard = className === STATE_STORE_CLASS ? 'No withStoreFallback' : 'No fallback covers this class';
  return `${change.says}. ${guard}: a caller rejects against an object still on the base build, `
    + `so its first caller lands a release later.${where || ' No call reaches it in this build.'}`;
}

export function formatReport({ base, head, verdict, read, labels, stale }) {
  const classes = Object.values(head.classes);
  const methods = classes.reduce((sum, entry) => sum + Object.keys(entry.methods).length, 0);
  const lines = [
    `RPC contract: ${classes.length} classes, ${methods} methods, ${Object.keys(head.types).length} types, `
      + `${Object.keys(head.payloads).length} payloads. Base ${labels.base}, head ${labels.head}.`,
  ];
  const line = (tag, change, text) => lines.push(`  ${tag.padEnd(8)} ${change.subject}${change.path ? ` ${change.path}` : ''}: ${text}`);
  for (const change of verdict.refused) line('refused', change, change.says);
  for (const change of verdict.accepted) line('accepted', change, `${change.says} (contract: ${change.reason})`);
  for (const change of verdict.noted) line('noted', change, describeAddition(change, head, read));
  if (verdict.refused.length) {
    const subjects = [...new Map(verdict.refused.map((change) => [change.subject, change.digest])).entries()];
    lines.push(
      `Refused ${verdict.refused.length} change${verdict.refused.length === 1 ? '' : 's'}. Make each one safe for both builds, `
        + 'or give its reason: why the two builds can serve side by side, and the release that makes it safe. '
        + `Either in ${SNAPSHOT}:`,
      '  "contract": {',
      ...subjects.map(([subject, digest], index) =>
        `    ${JSON.stringify(subject)}: { "to": "${digest}", "reason": "..." }${index < subjects.length - 1 ? ',' : ''}`),
      '  }',
      'or as a line in a commit message: contract: <subject>: <reason>',
    );
  }
  if (stale) lines.push(`${SNAPSHOT} does not match the source. Run npm run verify:rpc-contract -- --update and commit it.`);
  if (!verdict.refused.length && !stale) {
    lines.push(`RPC contract passed (${verdict.noted.length} noted, ${verdict.accepted.length} accepted).`);
  }
  return lines.join('\n');
}

export function run(argv, root = ROOT) {
  const options = parseArgs(argv);
  const baseRev = options.base ?? defaultBase(root);
  const labels = { base: `${shortRev(root, baseRev)}${options.base ? '' : ' (where HEAD leaves origin/main)'}` };

  let head;
  let read;
  let snapshot;
  const sections = [];
  if (options.head) {
    const committed = committedSnapshot(root, options.head);
    head = committed ? surfaceOf(committed) : surfaceAtRevision(root, options.head).surface;
    if (committed?.contract) sections.push(committed.contract);
    labels.head = `${shortRev(root, options.head)}${committed ? '' : ' (read from source)'}`;
  } else {
    read = readSurface(root);
    head = read.surface;
    const file = path.join(root, SNAPSHOT);
    snapshot = existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : undefined;
    labels.head = 'the working tree';
  }

  const baseCommitted = committedSnapshot(root, baseRev);
  const base = baseCommitted ? surfaceOf(baseCommitted) : surfaceAtRevision(root, baseRev).surface;
  if (!baseCommitted) labels.base += ', read from source';

  const range = `${baseRev}..${options.head ?? 'HEAD'}`;
  const inRange = reasonsInRange(root, range);
  sections.push(...inRange.sections);

  let stale = false;
  if (!options.head) {
    if (options.update) {
      const contract = keptReasons(snapshot?.contract, head);
      writeFileSync(path.join(root, SNAPSHOT), snapshotText(head, contract));
      snapshot = { contract };
    } else {
      stale = !snapshot || JSON.stringify(surfaceOf(snapshot)) !== JSON.stringify(head);
    }
    if (snapshot?.contract) sections.push(snapshot.contract);
  }

  const verdict = judge(compareSurfaces(base, head), head, {
    snapshotReasons: sections,
    commitReasons: commitReasons(inRange.messages),
  });
  return { ok: !stale && verdict.refused.length === 0, report: formatReport({ base, head, verdict, read, labels, stale }), verdict, stale };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const argv = process.argv.slice(2);
  if (argv.includes('--help')) {
    console.log('Usage: npm run verify:rpc-contract -- [--update] [--base REV] [--head REV]\n'
      + 'Judge the Durable Object RPC surface against the base commit\'s (default: where HEAD leaves origin/main).');
    process.exit(0);
  }
  try {
    const { ok, report } = run(argv);
    console.log(report);
    process.exitCode = ok ? 0 : 1;
  } catch (error) {
    console.error(error instanceof UsageError ? error.message : error?.stack ?? String(error));
    process.exitCode = 2;
  }
}
