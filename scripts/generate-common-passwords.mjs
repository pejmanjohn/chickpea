import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { dictionary } from '@zxcvbn-ts/language-common';

const root = fileURLToPath(new URL('..', import.meta.url));
const output = join(root, 'src', 'auth', 'generated-common-passwords.ts');
const sourcePackage = JSON.parse(readFileSync(
  join(root, 'node_modules', '@zxcvbn-ts', 'language-common', 'package.json'),
  'utf8',
));
if (sourcePackage.version !== '4.1.3') {
  throw new Error(`Expected @zxcvbn-ts/language-common@4.1.3, found ${sourcePackage.version}.`);
}
const selected = [];
const seen = new Set();

for (const raw of dictionary['passwords-common']) {
  const candidate = raw.normalize('NFKC').toLowerCase();
  const length = Array.from(candidate).length;
  if (length < 15 || length > 128 || seen.has(candidate)) continue;
  seen.add(candidate);
  selected.push(candidate);
}

// The pinned 4.1.3 corpus has only 41 entries that can pass Chickpea's
// 15-code-point minimum. Include every effective entry; shorter entries are
// unreachable after the length gate and would only inflate the Worker bundle.
if (selected.length !== 41) {
  throw new Error(`Expected 41 policy-eligible common passwords, found ${selected.length}.`);
}

const serialized = JSON.stringify(selected);
const digest = createHash('sha256').update(serialized).digest('hex');
const lines = [
  '// Generated by scripts/generate-common-passwords.mjs. Do not edit.',
  '// Source: @zxcvbn-ts/language-common@4.1.3 passwords-common (MIT).',
  '// Contains every source entry that satisfies the 15-128 code-point policy (41 total).',
  `// SHA-256 of the JSON array: ${digest}`,
  `export const COMMON_PASSWORDS_SHA256 = '${digest}';`,
  `export const COMMON_PASSWORDS_SOURCE_COUNT = ${dictionary['passwords-common'].length};`,
  'export const COMMON_PASSWORDS = [',
  ...selected.map((entry) => `  ${JSON.stringify(entry)},`),
  '] as const;',
  '',
].join('\n');

writeFileSync(output, lines, 'utf8');
console.log(`Wrote ${selected.length} entries to ${output} (${digest}).`);
